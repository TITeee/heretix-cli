// TestEnrichCargoLicensesFromCache_Container covers an image scan: CARGO_HOME
// names a path inside the scanned image (applyImageEnv sets it from the
// image's own declared ENV), which exists on this host only under the
// extracted rootfs. Also checks that an image which never declared
// CARGO_HOME finds nothing rather than falling back to this host's own
// ~/.cargo, which describes the scanning machine, not the image.
func TestEnrichCargoLicensesFromCache_Container(t *testing.T) {
	rootfs := t.TempDir()
	crateDir := filepath.Join(rootfs, "usr", "local", "cargo", "registry", "src", "index.crates.io-abc123", "anyhow-1.0.86")
	if err := os.MkdirAll(crateDir, 0o700); err != nil {
		t.Fatal(err)
	}
	manifest := "[package]\nname = \"anyhow\"\nversion = \"1.0.86\"\nlicense = \"MIT OR Apache-2.0\"\n"
	if err := os.WriteFile(filepath.Join(crateDir, "Cargo.toml"), []byte(manifest), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Setenv("CARGO_HOME", "/usr/local/cargo")

	pkgs := []inventory.Package{{Name: "anyhow", Version: "1.0.86"}}
	enrichCargoLicensesFromCache(pkgs, false, rootfs, true)
	if pkgs[0].License != "MIT OR Apache-2.0" {
		t.Errorf("License = %q, want %q (read from <rootfs>/usr/local/cargo/...)", pkgs[0].License, "MIT OR Apache-2.0")
	}

	os.Unsetenv("CARGO_HOME")
	pkgs2 := []inventory.Package{{Name: "anyhow", Version: "1.0.86"}}
	enrichCargoLicensesFromCache(pkgs2, false, rootfs, true)
	if pkgs2[0].License != "" {
		t.Errorf("License = %q, want \"\" (image declared no CARGO_HOME, so the host's own default must not be used)", pkgs2[0].License)
	}
}

func TestIsCargoRegistryDir(t *testing.T) {
	tests := []struct {
		path string
		want bool
	}{
		{"/usr/local/cargo/registry", true}, // official Rust Docker images
		{"/root/.cargo/registry", true},     // the common default
		{"/home/dev/.cargo/registry", true},
		{"/app/testproj/registry", false},        // "registry" not under a cargo home
		{"/usr/local/cargo/registry/src", false}, // registry's own child, not "registry" itself
		{"/usr/local/cargo", false},
	}
	for _, tt := range tests {
		if got := isCargoRegistryDir(tt.path); got != tt.want {
			t.Errorf("isCargoRegistryDir(%q) = %v, want %v", tt.path, got, tt.want)
		}
	}
}

// TestCollect_SkipsRegistryCache reproduces a bug found scanning a real built
// image: several published crates (anyhow, serde, syn, ...) ship their own
// Cargo.lock inside their source tarball, for building/testing that crate
// standalone. Without skipping CARGO_HOME/registry, walking into the
// extracted cache turned one real project's Cargo.lock into several,
// reporting crates the image never asked for.
func TestCollect_SkipsRegistryCache(t *testing.T) {
	dir := t.TempDir()
	projectLock := `[[package]]
name = "my-crate"
version = "0.1.0"
dependencies = [
 "anyhow",
]

[[package]]
name = "anyhow"
version = "1.0.86"
source = "registry+https://github.com/rust-lang/crates.io-index"
`
	if err := os.WriteFile(filepath.Join(dir, "Cargo.lock"), []byte(projectLock), 0o600); err != nil {
		t.Fatal(err)
	}

	cacheDir := filepath.Join(dir, "usr", "local", "cargo", "registry", "src", "index.crates.io-abc123", "anyhow-1.0.86")
	if err := os.MkdirAll(cacheDir, 0o700); err != nil {
		t.Fatal(err)
	}
	cachedLock := `[[package]]
name = "unrelated-dev-tool"
version = "9.9.9"
source = "registry+https://github.com/rust-lang/crates.io-index"
`
	if err := os.WriteFile(filepath.Join(cacheDir, "Cargo.lock"), []byte(cachedLock), 0o600); err != nil {
		t.Fatal(err)
	}

	pkgs, err := (&CargoCollector{}).Collect(dir, false, false)
	if err != nil {
		t.Fatal(err)
	}

	for _, p := range pkgs {
		if p.Name == "unrelated-dev-tool" {
			t.Fatalf("collected %q from inside CARGO_HOME/registry; that cache should have been skipped", p.Name)
		}
	}
	if len(pkgs) != 1 || pkgs[0].Name != "anyhow" {
		t.Errorf("got %v, want exactly [anyhow]", pkgs)
	}
}

func TestResolveCargoDepRef(t *testing.T) {
	versionsByName := map[string][]string{
		"unique":   {"1.0.0"},
		"multiple": {"1.0.0", "2.0.0"},
	}

	tests := []struct {
		ref     string
		name    string
		version string
		ok      bool
	}{
		{"unique", "unique", "1.0.0", true},
		{"multiple 2.0.0", "multiple", "2.0.0", true},
		{"multiple", "", "", false}, // ambiguous bare reference cannot be resolved
		{"unknown", "", "", false},
	}

	for _, tt := range tests {
		name, version, ok := resolveCargoDepRef(tt.ref, versionsByName)
		if name != tt.name || version != tt.version || ok != tt.ok {
			t.Errorf("resolveCargoDepRef(%q) = (%q, %q, %v), want (%q, %q, %v)",
				tt.ref, name, version, ok, tt.name, tt.version, tt.ok)
		}
	}
}
